package tui

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// syncSurfaceDocs compares every generated inventory file with what the current
// code produces: the index block in the overview doc and one file per audited
// package under surfaceInventoryDir. With surfaceUpdateEnv=1 it rewrites the
// stale files and removes per-package files no audited package produces.
func syncSurfaceDocs(t *testing.T, doc string, rows []surfaceRow) {
	t.Helper()

	updated, err := replaceSurfaceBlock(doc, renderSurfaceIndex(rows))
	if err != nil {
		t.Fatalf("%s: %v", surfaceDocPath, err)
	}
	want := map[string]string{surfaceDocPath: updated}
	byPkg := map[string][]surfaceRow{}
	for _, r := range rows {
		byPkg[r.pkg] = append(byPkg[r.pkg], r)
	}
	for _, pkg := range surfaceAuditedPackages {
		want[filepath.Join(surfaceInventoryDir, surfaceInventoryFile(pkg))] = renderSurfacePackage(pkg, byPkg[pkg])
	}

	existing, err := filepath.Glob(filepath.Join(surfaceInventoryDir, "*.md"))
	if err != nil {
		t.Fatalf("list %s: %v", surfaceInventoryDir, err)
	}
	var orphans []string
	for _, path := range existing {
		if _, ok := want[path]; !ok {
			orphans = append(orphans, path)
		}
	}

	update := os.Getenv(surfaceUpdateEnv) == "1"
	var stale []string
	for _, path := range sortedSurfacePaths(want) {
		got, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			t.Fatalf("read %s: %v", path, err)
		}
		if string(got) == want[path] {
			continue
		}
		stale = append(stale, path)
		if update {
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatalf("create %s: %v", filepath.Dir(path), err)
			}
			if err := os.WriteFile(path, []byte(want[path]), 0o644); err != nil {
				t.Fatalf("write %s: %v", path, err)
			}
			continue
		}
		t.Errorf("%s is stale: the committed inventory no longer matches the exported\n"+
			"declarations and uses in the module.\n%s", path, surfaceLineDiff(string(got), want[path]))
	}
	for _, path := range orphans {
		if update {
			if err := os.Remove(path); err != nil {
				t.Fatalf("remove %s: %v", path, err)
			}
			continue
		}
		t.Errorf("%s is not generated for any audited package; remove it", path)
	}
	if len(stale)+len(orphans) == 0 {
		return
	}
	if update {
		t.Fatalf("surface inventory regenerated (%d file(s)); rerun without %s=1", len(stale)+len(orphans), surfaceUpdateEnv)
	}
	t.Errorf("Regenerate with:\n\t%s=1 go test ./internal/tui -run TestExportedSurfaceInventoryCurrent", surfaceUpdateEnv)
}

func sortedSurfacePaths(files map[string]string) []string {
	paths := make([]string, 0, len(files))
	for path := range files {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	return paths
}

// surfaceInventoryFile names the per-package inventory file of an audited
// package after its short form: tui/keys is tui-keys.md.
func surfaceInventoryFile(pkg string) string {
	return strings.ReplaceAll(surfaceShortPkg(pkg), "/", "-") + ".md"
}

// renderSurfaceIndex is the generated block of the overview doc: the totals
// line, then a link to each per-package inventory file.
func renderSurfaceIndex(rows []surfaceRow) string {
	var b strings.Builder
	b.WriteString(surfaceTotals(rows) + "\n\n")
	for _, pkg := range surfaceAuditedPackages {
		fmt.Fprintf(&b, "- [`%s`](%s/%s)\n", surfaceShortPkg(pkg), filepath.Base(surfaceInventoryDir), surfaceInventoryFile(pkg))
	}
	return strings.TrimRight(b.String(), "\n")
}

// renderSurfacePackage is the whole content of one per-package inventory file.
func renderSurfacePackage(pkg string, rows []surfaceRow) string {
	var b strings.Builder
	short := surfaceShortPkg(pkg)
	fmt.Fprintf(&b, "# `%s` exported surface\n\n", short)
	b.WriteString("<!-- GENERATED by TestExportedSurfaceInventoryCurrent " +
		"(internal/tui/surface_inventory_test.go); do not edit by hand. -->\n\n")
	fmt.Fprintf(&b, "Per-identifier inventory of `%s`. The counting rules, the disposition legend and\n"+
		"the regeneration command are in\n"+
		"[TUI Package Exported Surface](../%s#per-identifier-inventory).\n\n",
		short, filepath.Base(surfaceDocPath))
	b.WriteString("| Package | Identifier | Kind | Importers | Disposition |\n")
	b.WriteString("|---|---|---|---|---|\n")
	for _, r := range rows {
		name := r.name
		if r.member == 1 {
			name = r.sortRecv + "." + r.name
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s |\n",
			short, name, r.kind, surfaceMarkupPkgs(r.importers), r.disposition)
	}
	return b.String()
}

// surfaceTotals is the one-line roll-up that opens the generated block, so the
// shape of the surface is readable without counting 800 rows by hand.
func surfaceTotals(rows []surfaceRow) string {
	var multi, single, testsOnly int
	zero := map[string]int{}
	for _, r := range rows {
		base, isTestsOnly := strings.CutSuffix(r.disposition, " (tests only)")
		if isTestsOnly {
			testsOnly++
		}
		switch {
		case base == "multi":
			multi++
		case base == "api", base == "json", strings.HasPrefix(base, "iface: "), strings.HasPrefix(base, "keep: "):
			zero[strings.SplitN(base, ":", 2)[0]]++
		default:
			single++
		}
	}
	kinds := make([]string, 0, len(zero))
	for _, kind := range []string{"api", "iface", "json", "keep"} {
		if n := zero[kind]; n > 0 {
			kinds = append(kinds, fmt.Sprintf("%d `%s`", n, kind))
		}
	}
	total := multi + single
	for _, n := range zero {
		total += n
	}
	return fmt.Sprintf("**%d exported identifiers across %d packages**: %d reached from two or more "+
		"packages, %d from exactly one, %d from none (%s). %d of the reached identifiers are named "+
		"only by `_test.go` files outside their own package.",
		total, len(surfaceAuditedPackages), multi, single, total-multi-single, strings.Join(kinds, ", "), testsOnly)
}

// surfaceMarkupPkgs code-quotes each package name in a comma-separated list.
func surfaceMarkupPkgs(list string) string {
	if list == "—" {
		return list
	}
	parts := strings.Split(list, ", ")
	for i, p := range parts {
		parts[i] = "`" + p + "`"
	}
	return strings.Join(parts, ", ")
}

func replaceSurfaceBlock(doc, block string) (string, error) {
	start := strings.Index(doc, surfaceBeginMarker)
	end := strings.Index(doc, surfaceEndMarker)
	if start < 0 || end < 0 || end < start {
		return "", fmt.Errorf("missing %s / %s markers around the generated inventory", surfaceBeginMarker, surfaceEndMarker)
	}
	return doc[:start+len(surfaceBeginMarker)] + "\n\n" + block + "\n\n" + doc[end:], nil
}

// surfaceLineDiff reports the first differing lines plus the size change, which
// is enough to see what moved without dumping an 800-row table into the log.
func surfaceLineDiff(got, want string) string {
	gotLines, wantLines := strings.Split(got, "\n"), strings.Split(want, "\n")
	var b strings.Builder
	fmt.Fprintf(&b, "committed rows: %d, current rows: %d\n", len(gotLines), len(wantLines))
	shown := 0
	for i := 0; i < len(gotLines) || i < len(wantLines); i++ {
		var g, w string
		if i < len(gotLines) {
			g = gotLines[i]
		}
		if i < len(wantLines) {
			w = wantLines[i]
		}
		if g == w {
			continue
		}
		if shown == 10 {
			b.WriteString("  ... (further differences omitted)\n")
			break
		}
		fmt.Fprintf(&b, "  line %d:\n    committed: %s\n    current:   %s\n", i+1, g, w)
		shown++
	}
	return strings.TrimRight(b.String(), "\n")
}
