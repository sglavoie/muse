#!/usr/bin/env python3
"""Print Casks/muse-player.rb for sglavoie/homebrew-tap.

On macOS the cask installs the notarized muse.app into /Applications and links
the muse it bundles, so the app and the command line are one signed binary that
one `brew upgrade` moves. On Linux it links muse from the release tarball.

The token is muse-player, not muse: homebrew/cask has an unrelated muse cask,
and an installed muse resolves to that one, so `brew upgrade` skipped ours.

Usage: homebrew_cask.py VERSION CHECKSUMS_TXT

VERSION has no leading v. CHECKSUMS_TXT is GoReleaser's checksums.txt, which
names the macOS and Linux archives.
"""

from pathlib import Path
import re
import sys


TOKEN = "muse-player"
REPO_URL = "https://github.com/sglavoie/muse"
SHA256 = re.compile(r"[0-9a-f]{64}")

CASK = """\
# This file is generated by muse's release workflow (scripts/homebrew_cask.py). DO NOT EDIT.
cask "{token}" do
  version "{version}"

  on_macos do
    sha256 "{darwin}"

    url "{repo}/releases/download/v#{{version}}/muse_#{{version}}_darwin_all.tar.gz"

    depends_on macos: :sonoma

    app "muse.app"
    binary "#{{appdir}}/muse.app/Contents/Resources/bin/muse"

    # The app's own state only: config and library under ~/.config/muse are the user's.
    zap trash: [
      "~/Library/Preferences/io.github.sglavoie.muse.plist",
      "~/Library/Saved Application State/io.github.sglavoie.muse.savedState",
    ]
  end
  on_linux do
    on_arm do
      sha256 "{linux_arm64}"

      url "{repo}/releases/download/v#{{version}}/muse_#{{version}}_linux_arm64.tar.gz"
    end
    on_intel do
      sha256 "{linux_amd64}"

      url "{repo}/releases/download/v#{{version}}/muse_#{{version}}_linux_amd64.tar.gz"
    end

    binary "muse"

    zap :not_required
  end

  name "muse"
  desc "Keyboard-driven terminal music player for your local library"
  homepage "{repo}"

  livecheck do
    url :url
    strategy :github_latest
  end

  # mpv plays; ExifTool is the recommended metadata backend (ffprobe also works).
  depends_on formula: [
    "exiftool",
    "mpv",
  ]
end
"""


def archive_sha(checksums, name):
    """Return the SHA-256 checksums.txt lists for the archive called name."""
    for line in checksums.splitlines():
        fields = line.split()
        if len(fields) == 2 and fields[1] == name and SHA256.fullmatch(fields[0]):
            return fields[0]
    raise ValueError(f"checksums.txt has no SHA-256 for {name}")


def render(version, checksums):
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError(f"not a version like 1.2.3 (no leading v): {version!r}")
    shas = {key: archive_sha(checksums, f"muse_{version}_{suffix}.tar.gz")
            for key, suffix in [("darwin", "darwin_all"),
                                ("linux_arm64", "linux_arm64"),
                                ("linux_amd64", "linux_amd64")]}
    return CASK.format(token=TOKEN, version=version, repo=REPO_URL, **shas)


def main(argv):
    if len(argv) != 3:
        print("usage: homebrew_cask.py VERSION CHECKSUMS_TXT", file=sys.stderr)
        return 2
    try:
        sys.stdout.write(render(argv[1], Path(argv[2]).read_text()))
    except ValueError as err:
        print(err, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
