def resolve(ref):
    kind, _, rest = ref.partition(":")
    if kind == "vendored":
        return MACOS_LICENSES / rest
    tag = re.search(r"^GHOSTTY_TAG=(\S+)", (ROOT / "macos" / "GHOSTTY_VERSION").read_text(), re.M).group(1)
    if kind == "ghostty":
        return MACOS_CACHE / f"ghostty-{tag}" / rest
    if kind == "zig":
        return MACOS_CACHE / "zig-global-cache" / "p" / rest
    raise ValueError(ref)


