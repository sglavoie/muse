ROOT = Path(__file__).resolve().parent.parent
GO_NOTICES = ROOT / "THIRD_PARTY_NOTICES.txt"
MACOS_NOTICES = ROOT / "macos" / "THIRD_PARTY_NOTICES-macos.txt"
MACOS_LICENSES = ROOT / "macos" / "licenses"
MACOS_CACHE = ROOT / "macos" / ".cache"

MODULE = "github.com/sglavoie/muse"
# GoReleaser's targets (.goreleaser.yaml); the module set is the union.
GO_TARGETS = [("linux", "amd64"), ("linux", "arm64"), ("darwin", "amd64"), ("darwin", "arm64")]
LICENSE_NAME = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|PATENTS)([-._].*)?$", re.IGNORECASE)

RULE = "=" * 79


# --- Go ---------------------------------------------------------------------


def go(*args, env=None):
    return subprocess.run(
        ["go", *args], cwd=ROOT, check=True, capture_output=True, text=True, env=env
    ).stdout


def linked_modules():
    """Module path -> (version, dir) for every module the release binaries link."""
    modules = {}
    for goos, goarch in GO_TARGETS:
        env = {**os.environ, "GOOS": goos, "GOARCH": goarch, "CGO_ENABLED": "0", "GOFLAGS": "-mod=mod"}
        out = go("list", "-deps", "-f", "{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}", ".", env=env)
        for line in out.splitlines():
            path, version, directory = line.split("\t")
            if path != MODULE:
                modules[path] = (version, directory)
    return modules


def license_files(directory):
    """License-like files at a module's root, sorted for a stable order."""
    return sorted(
        (p for p in Path(directory).iterdir() if p.is_file() and LICENSE_NAME.match(p.name)),
        key=lambda p: p.name.lower(),
    )


def go_notices():
    parts = [
        "Third-party notices for muse",
        "",
        "The muse binary is built with Go and links the Go modules below. Each",
        "section reproduces the license files the module ships. muse itself is",
        "MIT-licensed; see LICENSE. muse.app adds the components listed in",
        "muse.app/Contents/Resources/THIRD_PARTY_NOTICES-macos.txt.",
        "",
        "This file is generated by scripts/third_party_notices.py. DO NOT EDIT.",
        "",
    ]
    sections = [("The Go standard library and runtime", "https://go.dev", [ROOT / "scripts" / "licenses" / "go-LICENSE.txt"])]
    for path, (version, directory) in sorted(linked_modules().items(), key=lambda kv: kv[0].lower()):
        files = license_files(directory)
        if not files:
            raise SystemExit(f"{path} {version}: no license file in {directory}")
        sections.append((f"{path} {version}", f"https://pkg.go.dev/{path}@{version}", files))
    for title, url, files in sections:
        parts += section(title, url, files)
    return "\n".join(parts).rstrip("\n") + "\n"


