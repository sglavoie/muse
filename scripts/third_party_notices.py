#!/usr/bin/env python3
"""Write the third-party license notices that muse's release archives ship.

Two files, both committed so a release never depends on a local cache:

- THIRD_PARTY_NOTICES.txt: the Go standard library and every Go module linked
  into the muse binary for Linux or macOS (CGO_ENABLED=0, as GoReleaser
  builds it). Ships in every archive. Regenerating needs only `go`, so CI runs
  `--check go` to catch a dependency change that forgot to refresh it.
- macos/THIRD_PARTY_NOTICES-macos.txt: what muse.app adds on top of that:
  libghostty and the libraries GhosttyKit.xcframework links statically, its
  embedded fonts and themes, and the Swift ported from Ghostty's macOS app.
  Ships inside muse.app and in the macOS archive. Regenerating reads the
  Ghostty checkout and Zig package cache that `just mac-ghosttykit` leaves in
  macos/.cache, so rerun `third_party_notices.py macos` after bumping
  macos/GHOSTTY_VERSION, and re-check GHOSTTY_COMPONENTS against Ghostty's
  src/build/SharedDeps.zig for that tag.

Usage: third_party_notices.py [--check] {go,macos,all}
"""

from dataclasses import dataclass
from pathlib import Path
import argparse
import os
import re
import subprocess
